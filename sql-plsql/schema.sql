-- Create minimal tables for InterviewPrep examples (Oracle)
CREATE TABLE users (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username VARCHAR2(100) NOT NULL UNIQUE,
  email VARCHAR2(200),
  password_hash VARCHAR2(200),
  role VARCHAR2(20) DEFAULT 'USER',
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE questions (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  title VARCHAR2(250),
  type VARCHAR2(20),
  statement CLOB,
  difficulty VARCHAR2(20),
  created_by NUMBER,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE attempts (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  question_id NUMBER REFERENCES questions(id),
  user_id NUMBER REFERENCES users(id),
  correct NUMBER(1) DEFAULT 0,
  answered_at TIMESTAMP DEFAULT SYSTIMESTAMP
);
